"""Shared enums for models, statuses, and audit events."""

from enum import Enum


class IntentStatus(str, Enum):
    """Lifecycle statuses for buyer purchase intents."""

    PENDING = "PENDING"
    CLARIFICATION_NEEDED = "CLARIFICATION_NEEDED"
    VALIDATED = "VALIDATED"
    REJECTED = "REJECTED"


class QuoteStatus(str, Enum):
    """Lifecycle statuses for binding merchant quotes."""

    ACTIVE = "ACTIVE"
    APPROVED = "APPROVED"
    EXPIRED = "EXPIRED"
    INVALIDATED = "INVALIDATED"


class ApprovalStatus(str, Enum):
    """Lifecycle statuses for frozen buyer approval snapshots."""

    ACTIVE = "ACTIVE"
    CONSUMED = "CONSUMED"
    EXPIRED = "EXPIRED"
    INVALIDATED = "INVALIDATED"
    SUPERSEDED = "SUPERSEDED"


class PaymentAttemptStatus(str, Enum):
    """Statuses for PayPal payment attempts."""

    INITIATED = "INITIATED"
    PENDING = "PENDING"
    CAPTURED = "CAPTURED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class AuditEventType(str, Enum):
    """Immutable audit trail event types for intent and consent tracking."""

    QUOTE_CREATED = "QUOTE_CREATED"
    APPROVAL_GRANTED = "APPROVAL_GRANTED"
    PRODUCT_VERSION_CHANGED = "PRODUCT_VERSION_CHANGED"
    APPROVAL_INVALIDATED = "APPROVAL_INVALIDATED"
    PRE_CREATE_VALIDATION_FAILED = "PRE_CREATE_VALIDATION_FAILED"
    PRE_CREATE_VALIDATION_PASSED = "PRE_CREATE_VALIDATION_PASSED"
    PRE_CAPTURE_VALIDATION_FAILED = "PRE_CAPTURE_VALIDATION_FAILED"
    PRE_CAPTURE_VALIDATION_PASSED = "PRE_CAPTURE_VALIDATION_PASSED"


class ReasonCode(str, Enum):
    """Deterministic machine-readable reason codes for pre-create and pre-capture validation."""

    OK = "OK"
    APPROVAL_NOT_FOUND = "APPROVAL_NOT_FOUND"
    APPROVAL_EXPIRED = "APPROVAL_EXPIRED"
    APPROVAL_NOT_ACTIVE = "APPROVAL_NOT_ACTIVE"
    APPROVAL_SUPERSEDED = "APPROVAL_SUPERSEDED"
    APPROVAL_INVALIDATED = "APPROVAL_INVALIDATED"
    APPROVAL_ALREADY_CONSUMED = "APPROVAL_ALREADY_CONSUMED"
    QUOTE_INVALID = "QUOTE_INVALID"
    ITEM_MISMATCH = "ITEM_MISMATCH"
    MERCHANT_MISMATCH = "MERCHANT_MISMATCH"
    CURRENCY_MISMATCH = "CURRENCY_MISMATCH"
    QUANTITY_MISMATCH = "QUANTITY_MISMATCH"
    AMOUNT_MISMATCH = "AMOUNT_MISMATCH"
    QUOTE_CHANGED = "QUOTE_CHANGED"
    PRODUCT_VERSION_CHANGED = "PRODUCT_VERSION_CHANGED"
    POLICY_CHANGED = "POLICY_CHANGED"
    REQUIREMENTS_NO_LONGER_MET = "REQUIREMENTS_NO_LONGER_MET"
    PAYMENT_ATTEMPT_NOT_FOUND = "PAYMENT_ATTEMPT_NOT_FOUND"
    PAYMENT_ATTEMPT_UNBOUND = "PAYMENT_ATTEMPT_UNBOUND"
    VALIDATION_ERROR = "VALIDATION_ERROR"

